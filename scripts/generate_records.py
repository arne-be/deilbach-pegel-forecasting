"""Writes src/pegel/adapters/storage/records.py from the tables of a migrated database.

Usage: DATABASE_URL=... uv run python scripts/generate_records.py

Run it through scripts/refresh-schema.sh, which migrates a throwaway Postgres first.
The output depends only on the schema, so CI can regenerate it and diff.
"""

import os
import sys
from dataclasses import dataclass
from pathlib import Path

import psycopg

OUTPUT_PATH = Path(__file__).resolve().parents[1] / "src/pegel/adapters/storage/records.py"

# Only types the schema uses. An unknown type fails loudly instead of guessing.
PYTHON_TYPES = {
    "bigint": "int",
    "integer": "int",
    "text": "str",
    "double precision": "float",
    "timestamp with time zone": "datetime",
}

COLUMNS_QUERY = """
    SELECT table_name, column_name, data_type, is_nullable = 'YES'
    FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name <> 'schema_migrations'
    ORDER BY table_name, ordinal_position
"""


@dataclass(frozen=True)
class Column:
    table_name: str
    column_name: str
    data_type: str
    is_nullable: bool


def class_name(table_name: str) -> str:
    singular = table_name.removesuffix("s")
    return "".join(part.capitalize() for part in singular.split("_")) + "Record"


def python_type(column: Column) -> str:
    try:
        type_name = PYTHON_TYPES[column.data_type]
    except KeyError:
        raise ValueError(
            f"{column.table_name}.{column.column_name}: no Python type for {column.data_type!r}"
        ) from None
    return f"{type_name} | None" if column.is_nullable else type_name


def render(columns: list[Column]) -> str:
    tables: dict[str, list[Column]] = {}
    for column in columns:
        tables.setdefault(column.table_name, []).append(column)
    lines = [
        '"""Row types, one per table. Generated by scripts/generate_records.py, do not edit."""',
        "",
        "from dataclasses import dataclass",
        "from datetime import datetime",
    ]
    for table_name, table_columns in tables.items():
        lines += ["", "", "@dataclass(frozen=True)", f"class {class_name(table_name)}:"]
        lines += [f"    {column.column_name}: {python_type(column)}" for column in table_columns]
    return "\n".join(lines) + "\n"


def main() -> None:
    database_url = os.environ.get("DATABASE_URL")
    if not database_url:
        sys.exit("DATABASE_URL is not set")
    with psycopg.connect(database_url) as conn:
        columns = [Column(*row) for row in conn.execute(COLUMNS_QUERY)]
    if not columns:
        sys.exit("no tables found; migrate the database first")
    OUTPUT_PATH.write_text(render(columns), encoding="utf-8")
    print(f"wrote {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
